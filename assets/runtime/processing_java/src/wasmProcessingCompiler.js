  function buildRuntimeRequest(sketchBody, runtimeName) {
    return runtimeName === "cheerpj"
      ? buildCheerpJRequest(sketchBody)
      : buildTeaVmRequest(sketchBody);
  }

  function summarizeOutputs(outputs) {
    if (!outputs || !outputs.length) {
      return "No emitted browser artifacts yet.";
    }

    return outputs.map(function (file) {
      return "- " + file.path + (file.bytes ? " (" + file.bytes + " bytes)" : "");
    }).join("\n");
  }

