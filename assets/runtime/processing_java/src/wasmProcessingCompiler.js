  function createPreparedResult(request) {
    return request.runtime === "cheerpj"
      ? createCheerpJPreparedResult(request)
      : createTeaVmPreparedResult(request);
  }

  async function compileProcessingToWasmTarget(sketchBody, runtimeName) {
    var selectedRuntime = runtimeName === "cheerpj" ? "cheerpj" : "teavm";
    var request = buildRuntimeRequest(sketchBody, selectedRuntime);
    var javaSource = request.files[0].content;
    var adapter = window.WasmProcessingCompiler;

    if (!adapter || typeof adapter.compile !== "function") {
      var prepared = createPreparedResult(request);
      return {
        status: prepared.status,
        javaSource: javaSource,
        request: request,
        log: prepared.log + "\n\nPrepared files:\n" + summarizeOutputs(prepared.outputs),
        diagnostics: [],
        artifact: prepared
      };
    }

    try {
      var result = await adapter.compile(request);
      return {
        status: result && result.status ? result.status : "compiled",
        javaSource: javaSource,
        request: request,
        log: result && result.log ? result.log : summarizeOutputs(result && result.outputs),
        diagnostics: result && result.diagnostics ? result.diagnostics : [],
        classOutputs: result && result.classOutputs ? result.classOutputs : [],
        cheerpj: result && result.cheerpj ? result.cheerpj : null,
        artifact: result || null
      };
    } catch (error) {
      return {
        status: "compile-error",
        javaSource: javaSource,
        request: request,
        log: (error && error.stack) ? error.stack : String(error),
        diagnostics: [],
        artifact: null
      };
    }
  }

